AUTH_SESSION_TTL_SECONDS = 1800
MAX_QUERY_LENGTH = 1200
MAX_USSD_LENGTH = 600
MAX_FAILED_ATTEMPTS = 5
LOCKOUT_SECONDS = 300
DOC_ID_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9-]{0,79}$")
GROUP_PATTERN = re.compile(r"^[A-Za-z][A-Za-z0-9 -]{0,39}$")
EVERYONE = "Everyone"
