# ── Emergency alerts ───────────────────────────────────────────────────────────
# Stored in the audit table (record_type ALERT / ALERT_ACK) so no new AWS
# resources are needed. Anyone may raise an alert; only Clinical staff see them.

CLINICAL_GROUP = "Clinical"
ALERT_ID_PATTERN = re.compile(r"^[0-9a-f-]{36}$")


def require_clinical(principal: dict) -> None:
    if CLINICAL_GROUP not in principal.get("groups", []):
        raise ArchiveError(403, "Emergency alerts are only available to clinical staff.")


def _coordinate(value, low: float, high: float) -> str:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return ""
    return f"{number:.5f}" if low <= number <= high else ""


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")


PATIENT_ID_PATTERN = re.compile(r"^PAT-\d{3,6}$")


def _alert_identity(body: dict, principal: dict, users_table) -> tuple[dict, str, str]:
    """Decide who raised the alert. Returns (principal, identity, claimed_patient_id).

    identity is one of:
      verified_patient  signed in, or patient ID + correct PIN in the alert form
      staff             signed in as clinic staff (no patient record)
      claimed_patient   patient ID given without a correct PIN (shown as unverified)
      unregistered      no ID given
    A wrong PIN never blocks an emergency alert; it only leaves the identity unverified.
    """
    if principal["user_id"] != PUBLIC_PRINCIPAL["user_id"]:
        is_patient = any(g.startswith("PAT-") for g in principal.get("groups", []))
        return principal, ("verified_patient" if is_patient else "staff"), ""
    claimed = _optional_text(body, "patient_id", 20).upper()
    if not claimed or not PATIENT_ID_PATTERN.fullmatch(claimed):
        return principal, "unregistered", ""
    pin = _optional_text(body, "pin", 32)
    if pin:
        try:
            verified = authenticate(claimed, pin, users_table)
            if claimed in verified.get("groups", []):
                return verified, "verified_patient", ""
        except ArchiveError:
            pass
    return principal, "claimed_patient", claimed


def create_alert(body: dict, principal: dict, clients: dict, config: dict) -> dict:
    audit_table, users_table = clients["audit_table"], clients["users_table"]
    message = _optional_text(body, "message", 1000)
    lat = _coordinate(body.get("lat"), -90, 90)
    lng = _coordinate(body.get("lng"), -180, 180)
    image = decode_image(body)
    if not message and not (lat and lng) and not image:
        raise ArchiveError(400, "Describe what is happening, add a photo or share your location so the clinic can help.")
    principal, identity, claimed = _alert_identity(body, principal, users_table)
    registered = identity in ("verified_patient", "staff")
    patient_ids = [g for g in principal.get("groups", []) if g.startswith("PAT-")]
    timestamp = _now_iso()
    alert_id = str(uuid.uuid4())
    item = {
        "user_id": principal["user_id"] if registered else "PUBLIC",
        "timestamp_request": f"{timestamp}#{alert_id}",
        "record_type": "ALERT",
        "alert_id": alert_id,
        "timestamp": timestamp,
        "registered": registered,
        "identity": identity,
        "claimed_patient_id": claimed,
        "name": principal["name"] if registered else (_optional_text(body, "name", 100) or "Unregistered person"),
        "phone": _optional_text(body, "phone", 30),
        "patient_ids": patient_ids,
        "message": message,
        "channel": _optional_text(body, "channel", 10) or "web",
        "lat": lat,
        "lng": lng,
        "accuracy_m": _coordinate(body.get("accuracy"), 0, 100000),
        "image_key": "",
        "image_assessment": {},
    }
    if image:
        raw, fmt, ext, mime = image
        key = f"alerts/{alert_id}.{ext}"
        try:
            clients["s3"].put_object(Bucket=config["archive_bucket"], Key=key, Body=raw, ContentType=mime)
            item["image_key"] = key
        except ClientError:
            logger.exception("Could not store the photo for alert %s.", alert_id)
        try:
            item["image_assessment"] = assess_photo(raw, fmt, message, clients["bedrock_runtime"], config["generation_model_arn"])
        except ArchiveError:
            item["image_assessment"] = {"description": "", "urgency": "unknown", "error": "The photo could not be read automatically."}
    audit_table.put_item(Item=item)
    if identity == "verified_patient" and patient_ids:
        try:
            item["record_doc_id"] = write_event_record(clients, config, item, patient_ids[0], None)
        except ClientError:
            logger.exception("Could not file alert %s in the patient's record.", alert_id)
    # Secret that lets the sender's phone keep updating its live location.
    update_key = secrets.token_urlsafe(24)
    audit_table.put_item(Item={
        "user_id": f"ALERT#{alert_id}",
        "timestamp_request": "0#key",
        "record_type": "ALERT_KEY",
        "timestamp": timestamp,
        "key_hash": hashlib.sha256(update_key.encode("utf-8")).hexdigest(),
    })
    logger.warning("EMERGENCY ALERT %s from %s identity=%s patients=%s claimed=%s",
                   alert_id, item["user_id"], identity, patient_ids, claimed)
    return {
        "alert_id": alert_id,
        "timestamp": timestamp,
        "status": "sent",
        "identity": identity,
        "update_key": update_key,
        "image_assessment": item["image_assessment"],
        "record_doc_id": item.get("record_doc_id", ""),
    }


EVENT_PREFIX = "archive/Emergencies/"


def event_doc_id(alert_id: str) -> str:
    return "EVT-" + alert_id.replace("-", "")[:8].upper()


def _fmt_time(iso: str) -> str:
    return iso.replace("T", " ")[:16] + " UTC" if iso else ""


def build_event_text(alert: dict, patient_id: str, handling: dict | None) -> str:
    doc_id = event_doc_id(alert["alert_id"])
    identity = {
        "verified_patient": "verified (signed in or correct PIN)",
        "claimed_patient": "confirmed by clinic staff by phone",
    }.get(alert.get("identity", ""), alert.get("identity", ""))
    lines = [
        "========================================================================",
        "HOPEWELL COMMUNITY CLINIC",
        "FICTIONAL DEMONSTRATION RECORD - NOT REAL PATIENT DATA",
        "========================================================================",
        f"EMERGENCY RECORD - {alert.get('name', '')}".upper(),
        f"Document ID: {doc_id}",
        f"Date: {alert.get('timestamp', '')[:10]}",
        "========================================================================",
        f"Patient: {patient_id} {alert.get('name', '')}",
        f"Identity: {identity}",
        f"Reported: {_fmt_time(alert.get('timestamp', ''))} via {alert.get('channel', 'web')}",
    ]
    if alert.get("phone"):
        lines.append(f"Call-back number: {alert['phone']}")
    lat, lng = alert.get("lat", ""), alert.get("lng", "")
    home = PATIENT_HOMES.get(patient_id) or {}
    if lat and lng:
        where = f"Location when reported: {lat}, {lng}"
        if home.get("lat") is not None:
            km = _haversine_km(float(lat), float(lng), float(home["lat"]), float(home["lng"]))
            where += f" (about {km:.1f} km from home: {home.get('address', '')})"
        lines.append(where)
    else:
        lines.append("Location when reported: not shared")
    lines += ["", "PATIENT'S OWN WORDS", alert.get("message") or "(no message)"]
    assessment = alert.get("image_assessment") or {}
    if alert.get("image_key") or assessment.get("description"):
        lines += ["", "PHOTO SENT BY THE PATIENT",
                  f"AI description (triage support, not a diagnosis): {assessment.get('description', 'not available')}",
                  f"Urgency estimated from the photo: {assessment.get('urgency', 'unknown')}"]
        if assessment.get("first_aid_topic") and assessment["first_aid_topic"] != "none":
            lines.append(f"First-aid guide suggested to the patient: {assessment['first_aid_topic']} ({assessment.get('guide_doc_id', '')})")
    lines += ["", "HANDLING"]
    if handling:
        lines += [
            f"Handled by: {handling['by_name']} ({handling['by_id']})",
            f"Handled at: {_fmt_time(handling['at'])}",
            f"Outcome: {handling.get('outcome') or 'not recorded'}",
            f"What was done: {handling.get('notes') or 'not recorded'}",
        ]
    else:
        lines.append("Status: open - not yet handled by clinic staff")
    lines += ["", "------------------------------------------------------------------------",
              "Filed automatically from an emergency alert in Ask the Archive."]
    return "\n".join(lines) + "\n"


def _haversine_km(lat1: float, lng1: float, lat2: float, lng2: float) -> float:
    import math
    r = math.radians
    h = math.sin(r(lat2 - lat1) / 2) ** 2 + math.cos(r(lat1)) * math.cos(r(lat2)) * math.sin(r(lng2 - lng1) / 2) ** 2
    return 6371 * 2 * math.asin(math.sqrt(h))


def write_event_record(clients: dict, config: dict, alert: dict, patient_id: str, handling: dict | None) -> str:
    """File the emergency in the patient's record (DynamoDB now; S3 for the next Knowledge Base sync)."""
    doc_id = event_doc_id(alert["alert_id"])
    title = f"Emergency Record - {alert.get('name') or patient_id} - {alert.get('timestamp', '')[:10]}"
    groups = ["Clinical", patient_id]
    s3_key = f"{EVENT_PREFIX}{doc_id}_Emergency_Record_{patient_id}.txt"
    text = build_event_text(alert, patient_id, handling)
    clients["audit_table"].put_item(Item={
        "user_id": f"RECORD#{patient_id}",
        "timestamp_request": f"{alert.get('timestamp', '')}#{alert['alert_id']}",
        "record_type": "EVENT_RECORD",
        "timestamp": _now_iso(),
        "doc_id": doc_id,
        "alert_id": alert["alert_id"],
        "title": title,
        "patient_id": patient_id,
        "date": alert.get("timestamp", "")[:10],
        "groups": groups,
        "s3_key": s3_key,
        "image_key": alert.get("image_key", ""),
        "text": text,
    })
    try:
        meta = {"metadataAttributes": {
            "documentId": doc_id, "doc_id": doc_id, "title": title, "documentType": "Emergency Record",
            "folder": "Emergencies", "accessGroups": groups, "patientId": patient_id,
            "documentDate": alert.get("timestamp", "")[:10],
            **{group_key(g): "yes" for g in groups},
        }}
        clients["s3"].put_object(Bucket=config["archive_bucket"], Key=s3_key, Body=text.encode("utf-8"),
                                 ContentType="text/plain; charset=utf-8")
        clients["s3"].put_object(Bucket=config["archive_bucket"], Key=f"{s3_key}.metadata.json",
                                 Body=json.dumps(meta).encode("utf-8"), ContentType="application/json")
    except ClientError:
        logger.exception("Could not copy emergency record %s to S3 (it is still in the record store).", doc_id)
    refresh_events(clients["audit_table"], force=True)
    return doc_id


def refresh_events(audit_table, force: bool = False) -> None:
    """Reload emergency records into the dynamic catalogue (cached for a few seconds)."""
    global _EVENTS_LOADED_AT
    if not force and time.time() - _EVENTS_LOADED_AT < EVENT_REFRESH_SECONDS:
        return
    from boto3.dynamodb.conditions import Key as DKey
    try:
        items = audit_table.query(
            IndexName="ByTimestamp",
            KeyConditionExpression=DKey("record_type").eq("EVENT_RECORD"),
            ScanIndexForward=False,
            Limit=300,
        ).get("Items", [])
    except ClientError:
        logger.exception("Could not load emergency records.")
        return
    docs, keys = {}, {}
    for item in items:
        if item.get("record_type") != "EVENT_RECORD" or not item.get("doc_id") or item["doc_id"] in docs:
            continue
        docs[item["doc_id"]] = {
            "doc_id": item["doc_id"],
            "title": item.get("title", item["doc_id"]),
            "type": "Emergency Record",
            "folder": "Emergencies",
            "date": item.get("date", ""),
            "patient_id": item.get("patient_id", ""),
            "groups": list(item.get("groups", [])),
            "s3_key": item.get("s3_key", ""),
            "text": item.get("text", ""),
            **({"scan_key": item["image_key"], "attachment": "photo"} if item.get("image_key") else {}),
        }
        if item.get("s3_key"):
            keys[item["s3_key"]] = item["doc_id"]
    EVENT_DOCS.clear(); EVENT_DOCS.update(docs)
    EVENT_KEYS.clear(); EVENT_KEYS.update(keys)
    _EVENTS_LOADED_AT = time.time()


def update_alert_location(body: dict, audit_table) -> dict:
    """The sender's phone reports where it is now (live tracking)."""
    alert_id = _optional_text(body, "alert_id", 36)
    if not ALERT_ID_PATTERN.fullmatch(alert_id):
        raise ArchiveError(400, "The alert ID is invalid.")
    key = _optional_text(body, "update_key", 64)
    stored = audit_table.get_item(Key={"user_id": f"ALERT#{alert_id}", "timestamp_request": "0#key"}).get("Item")
    expected = stored.get("key_hash", "") if isinstance(stored, dict) else ""
    if not key or not expected or not hmac.compare_digest(hashlib.sha256(key.encode("utf-8")).hexdigest(), expected):
        raise ArchiveError(403, "This device cannot update that alert.")
    lat = _coordinate(body.get("lat"), -90, 90)
    lng = _coordinate(body.get("lng"), -180, 180)
    if not (lat and lng):
        raise ArchiveError(400, "A location is required.")
    timestamp = _now_iso()
    audit_table.put_item(Item={
        "user_id": f"ALERT#{alert_id}",
        "timestamp_request": f"{timestamp}#loc",
        "record_type": "ALERT_LOC",
        "alert_id": alert_id,
        "timestamp": timestamp,
        "lat": lat,
        "lng": lng,
        "accuracy_m": _coordinate(body.get("accuracy"), 0, 100000),
        "simulated": body.get("simulated") is True,
    })
    return {"alert_id": alert_id, "status": "updated", "timestamp": timestamp}


def _alert_track(audit_table, alert_id: str) -> list:
    from boto3.dynamodb.conditions import Key as DKey
    result = audit_table.query(
        KeyConditionExpression=DKey("user_id").eq(f"ALERT#{alert_id}"),
        ScanIndexForward=False,
        Limit=40,
    )
    points = [
        {"lat": i.get("lat", ""), "lng": i.get("lng", ""), "timestamp": i.get("timestamp", ""),
         "accuracy_m": i.get("accuracy_m", ""), "simulated": bool(i.get("simulated"))}
        for i in result.get("Items", [])
        if i.get("record_type") == "ALERT_LOC" and i.get("user_id") == f"ALERT#{alert_id}"
    ]
    return list(reversed(points))  # oldest first


def list_alerts(audit_table, s3_client=None, archive_bucket: str = "") -> list:
    from boto3.dynamodb.conditions import Key as DKey

    def query(record_type: str, limit: int) -> list:
        result = audit_table.query(
            IndexName="ByTimestamp",
            KeyConditionExpression=DKey("record_type").eq(record_type),
            ScanIndexForward=False,
            Limit=limit,
        )
        return [i for i in result.get("Items", []) if i.get("record_type") == record_type]

    acks = {a.get("alert_id"): a for a in query("ALERT_ACK", 200)}
    alerts = []
    for item in query("ALERT", 50):
        ack = acks.get(item.get("alert_id"))
        patient = (list(item.get("patient_ids", [])) or [item.get("claimed_patient_id", "")])[0]
        image_url = ""
        if item.get("image_key") and s3_client is not None and archive_bucket:
            image_url = s3_client.generate_presigned_url(
                "get_object", Params={"Bucket": archive_bucket, "Key": item["image_key"]}, ExpiresIn=SOURCE_URL_TTL_SECONDS,
            )
        alerts.append({
            "alert_id": item.get("alert_id", ""),
            "timestamp": item.get("timestamp", ""),
            "registered": bool(item.get("registered")),
            "identity": item.get("identity") or ("verified_patient" if item.get("patient_ids") else "unregistered"),
            "claimed_patient_id": item.get("claimed_patient_id", ""),
            "user_id": item.get("user_id", ""),
            "name": item.get("name", ""),
            "phone": item.get("phone", ""),
            "patient_ids": list(item.get("patient_ids", [])),
            "message": item.get("message", ""),
            "channel": item.get("channel", "web"),
            "lat": item.get("lat", ""),
            "lng": item.get("lng", ""),
            "accuracy_m": item.get("accuracy_m", ""),
            "status": "handled" if ack else "open",
            "handled_by": ack.get("handled_by", "") if ack else "",
            "handled_at": ack.get("timestamp", "") if ack else "",
            "outcome": ack.get("outcome", "") if ack else "",
            "notes": ack.get("notes", "") if ack else "",
            "record_doc_id": (ack.get("record_doc_id") if ack else "") or (
                event_doc_id(item.get("alert_id", "")) if item.get("identity") == "verified_patient" and item.get("patient_ids") else ""),
            "home": PATIENT_HOMES.get(patient, {}) if patient else {},
            "track": _alert_track(audit_table, item.get("alert_id", "")) if not ack else [],
            "image_url": image_url,
            "image_assessment": item.get("image_assessment") or {},
        })
    return alerts


OUTCOMES = {"Treated at home", "Brought to the clinic", "Sent to hospital", "Advice by phone", "Ambulance called", "No action needed", "Could not reach the person"}


def _find_alert(audit_table, alert_id: str) -> dict | None:
    from boto3.dynamodb.conditions import Key as DKey
    items = audit_table.query(
        IndexName="ByTimestamp",
        KeyConditionExpression=DKey("record_type").eq("ALERT"),
        ScanIndexForward=False,
        Limit=200,
    ).get("Items", [])
    return next((i for i in items if i.get("record_type") == "ALERT" and i.get("alert_id") == alert_id), None)


def acknowledge_alert(body: dict, principal: dict, clients: dict, config: dict) -> dict:
    """Mark an alert handled, record what was done, and file it in the patient's record."""
    audit_table = clients["audit_table"]
    alert_id = _optional_text(body, "alert_id", 36)
    if not ALERT_ID_PATTERN.fullmatch(alert_id):
        raise ArchiveError(400, "The alert ID is invalid.")
    notes = _optional_text(body, "notes", 1500)
    outcome = _optional_text(body, "outcome", 60)
    if outcome and outcome not in OUTCOMES:
        raise ArchiveError(400, "Choose one of the listed outcomes.")
    timestamp = _now_iso()
    record_doc_id = ""
    alert = _find_alert(audit_table, alert_id)
    if alert and body.get("file_to_record") is True:
        patient = ""
        if alert.get("identity") == "verified_patient" and alert.get("patient_ids"):
            patient = list(alert["patient_ids"])[0]
        elif alert.get("identity") == "claimed_patient" and body.get("identity_confirmed") is True:
            patient = alert.get("claimed_patient_id", "")
        if patient:
            record_doc_id = write_event_record(clients, config, alert, patient, {
                "by_name": principal["name"], "by_id": principal["user_id"], "at": timestamp,
                "notes": notes, "outcome": outcome,
            })
    audit_table.put_item(Item={
        "user_id": principal["user_id"],
        "timestamp_request": f"{timestamp}#ack#{alert_id}",
        "record_type": "ALERT_ACK",
        "alert_id": alert_id,
        "timestamp": timestamp,
        "handled_by": principal["name"],
        "notes": notes,
        "outcome": outcome,
        "record_doc_id": record_doc_id,
    })
    return {"alert_id": alert_id, "status": "handled", "record_doc_id": record_doc_id}


# ── Main dispatcher ────────────────────────────────────────────────────────────

def dispatch(body: dict, clients: dict, config: dict, auth_header: str = "") -> tuple[int, dict]:
    """
    Route a parsed request dict to the right handler.
    auth_header: the raw Authorization header value from the HTTP request.
    """
    action  = _optional_text(body, "action", 32)
    user_id = _optional_text(body, "user_id", 128).upper()

    # ── verify: PIN login → returns session token ────────────────────────────
    if action == "verify":
        pin = _required_text(body, "pin", 32)
        principal = authenticate(user_id, pin, clients["users_table"])
        token = issue_session(principal, clients["sessions_table"])
        return 200, {
            "authenticated": True,
            "user_id": principal["user_id"],
            "name": principal["name"],
            "role": principal["role"],
            "groups": principal["groups"],
            "scope": scope_label(principal),
            "token": token,
        }

    # ── All other actions: bearer token or public fallback ───────────────────
    if auth_header and auth_header.startswith("Bearer "):
        principal = authenticate_session(auth_header, clients)
    else:
        principal = dict(PUBLIC_PRINCIPAL)

    if action in {"documents", "document", "ask", "summary", "extract", "ussd"}:
        refresh_events(clients["audit_table"])

    if action == "documents":
        return 200, {"documents": document_summaries(principal), "scope": scope_label(principal)}

    if action == "ask":
        channel = _optional_text(body, "channel", 10)
        if channel not in {"web", "voice", "ussd"}:
            raise ArchiveError(400, "The request channel is invalid.")
        question = _required_text(body, "query", MAX_QUERY_LENGTH)
        return 200, _run_answer(question, channel, principal, "", clients, config)

    if action == "summary":
        channel = _optional_text(body, "channel", 10)
        if channel not in {"web", "voice", "ussd"}:
            raise ArchiveError(400, "The request channel is invalid.")
        question = _required_text(body, "query", MAX_QUERY_LENGTH)
        doc_id   = _required_text(body, "doc_id", 80)
        if not DOC_ID_PATTERN.fullmatch(doc_id):
            raise ArchiveError(400, "The requested document ID is invalid.")
        return 200, _run_answer(question, channel, principal, doc_id, clients, config)

    if action == "logs":
        if principal["user_id"] == PUBLIC_PRINCIPAL["user_id"]:
            raise ArchiveError(403, "Sign in to see the question history.")
        from boto3.dynamodb.conditions import Key as DKey
        # Staff audit everyone; patients see their own questions.
        if set(principal["groups"]) & AUDIT_ALL_GROUPS:
            result = clients["audit_table"].query(
                IndexName="ByTimestamp",
                KeyConditionExpression=DKey("record_type").eq("ARCHIVE"),
                ScanIndexForward=False,
                Limit=100,
            )
        else:
            result = clients["audit_table"].query(
                KeyConditionExpression=DKey("user_id").eq(principal["user_id"]),
                ScanIndexForward=False,
                Limit=50,
            )
        entries = [
            {
                "timestamp": item["timestamp"],
                "user_id": item["user_id"],
                "role": item["role"],
                "channel": item["channel"],
                "question": item["question"],
                "status": item["status"],
                "sources": item.get("sources", []),
            }
            for item in result.get("Items", [])
            if item.get("record_type", "ARCHIVE") == "ARCHIVE"
        ]
        return 200, {"logs": entries}

    if action == "document":
        doc_id = _required_text(body, "doc_id", 80)
        document = get_doc(doc_id)
        if document is None or not can_read(principal, document):
            raise ArchiveError(404, "That document is not available to you.")
        result = {k: document.get(k, "") for k in ("doc_id", "title", "type", "date", "patient_id", "text")}
        if document.get("scan_key"):
            result["attachment"] = document.get("attachment", "scan")
            result["scan_url"] = clients["s3"].generate_presigned_url(
                "get_object", Params={"Bucket": config["archive_bucket"], "Key": document["scan_key"]},
                ExpiresIn=SOURCE_URL_TTL_SECONDS,
            )
        return 200, result

    if action == "extract":
        doc_id = _required_text(body, "doc_id", 80)
        return 200, extract_details(doc_id, principal, clients["bedrock_runtime"], config["generation_model_arn"])

    if action == "ocr":
        if "Staff" not in principal.get("groups", []):
            raise ArchiveError(403, "Only clinic staff can scan documents.")
        image = decode_image(body)
        if not image:
            raise ArchiveError(400, "Send the scanned page as an image.")
        raw, fmt, _ext, _mime = image
        return 200, {"text": ocr_image(raw, fmt, clients["bedrock_runtime"], config["generation_model_arn"])}

    if action == "alert_location":
        return 200, update_alert_location(body, clients["audit_table"])

    if action == "alert_create":
        return 200, create_alert(body, principal, clients, config)

    if action == "alert_list":
        require_clinical(principal)
        return 200, {"alerts": list_alerts(clients["audit_table"], clients["s3"], config["archive_bucket"])}

    if action == "alert_ack":
        require_clinical(principal)
        return 200, acknowledge_alert(body, principal, clients, config)

    if action == "ussd":
        return 200, handle_ussd(body, clients, config)

    raise ArchiveError(400, "The requested archive action is not supported.")
