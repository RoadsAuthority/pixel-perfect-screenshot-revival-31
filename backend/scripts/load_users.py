"""Write the demo users in backend/demo-users/*.json into the DynamoDB users table.

Usage:  python backend/scripts/load_users.py

Reads AWS settings from backend/.env. Existing items with the same user_id are replaced.
PINs are stored only as salted hashes (generated by prepare_archive.py).
"""

import json
import os
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]


def load_env() -> None:
    for line in (BACKEND / ".env").read_text(encoding="utf-8-sig").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            os.environ[key.strip()] = value.strip().strip('"').strip("'")


def main() -> None:
    load_env()
    import boto3
    from botocore.exceptions import ClientError

    ddb = boto3.client("dynamodb", region_name=os.environ["AWS_REGION"])
    table = os.environ["AUTH_USERS_TABLE"]
    for path in sorted((BACKEND / "demo-users").glob("*.json")):
        item = json.loads(path.read_text(encoding="utf-8"))
        try:
            ddb.put_item(TableName=table, Item=item)
            print(f"ok    {item['user_id']['S']}")
        except ClientError as err:
            print(f"FAIL  {item['user_id']['S']}: {err.response['Error']['Code']}")
            raise SystemExit("Add the users by hand in the DynamoDB console instead (Create item -> JSON view).")


if __name__ == "__main__":
    main()
